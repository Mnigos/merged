/** An ISO 3166-1 alpha-2 code of a country in `COUNTRIES`, lowercase. */
export type CountryCode = (typeof COUNTRIES)[number]['code']

/**
 * Phrases that name a region spanning several countries, so the country
 * names inside them do not count: "Latin America" is not the United States.
 */
export const MULTI_COUNTRY_PHRASES = [
	'Latin America',
	'South America',
	'Central America',
	'North America',
	'América Latina',
	'Southeast Asia',
	'Asia Pacific',
] as const satisfies readonly string[]

/** A country of `COUNTRIES`, with its literal code. */
export type Country = (typeof COUNTRIES)[number]

const COUNTRY_BY_CODE: ReadonlyMap<string, Country> = new Map(
	COUNTRIES.map(country => [country.code, country])
)

/** The country with this ISO 3166-1 alpha-2 code, compared lowercase. */
export const findCountry = (code: string) =>
	COUNTRY_BY_CODE.get(code.toLowerCase())

/** Distance from a lowercase ASCII letter to its regional indicator symbol: `a` → 🇦. */
const REGIONAL_INDICATOR_OFFSET = 0x1_f1_e6 - 0x61

/** The flag emoji of a country code: two regional indicator symbols, `pl` → 🇵🇱. */
export const toFlag = (code: string) =>
	String.fromCodePoint(
		...code
			.toLowerCase()
			.split('')
			.map(letter => (letter.codePointAt(0) ?? 0) + REGIONAL_INDICATOR_OFFSET)
	)
