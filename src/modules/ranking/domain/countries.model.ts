/** A country or territory and the words that place a free-text location in it. */
export interface CountryEntry {
	/** ISO 3166-1 alpha-2, lowercase. */
	readonly code: string
	/** English short name, as boards show it. */
	readonly name: string
	/** Names in the country's own languages and scripts. */
	readonly nativeNames?: readonly string[]
	/** Other names: short forms, exonyms in other languages, and regions such as US states. */
	readonly aliases?: readonly string[]
	/** Short or ambiguous words, such as `pl` or `ca` for California, that count only when no country name or city matches. */
	readonly weakAliases?: readonly string[]
}

